#!/usr/bin/env node
/**
 * 为 IM 专用 profile 启用 dsh agent preset（能力档位）模式。
 *
 * 做法（与 README「IM 专用 profile 的 preset 组成」一致）：
 *  1. 从 dsh 安装目录里的 dsh-web-app bundle 抄一份「禁用 agent 平面行」清单
 *     （tool-bash/tool-fs/tool-skill/... —— 否则与 preset 内同名工具重复注册）；
 *  2. insert Host 侧模块 subagent-model-selection-settings（standard preset 的
 *     tool-subagent 依赖它）与 agent-preset-registry（agentPresets 服务）；
 *  3. 把 dsh-web-app 的 4 个 preset 定义（standard/ptc/minimal/cordis）原样追加，
 *     这样 AI 面板「Agent 模式」才有可选项。
 *
 * 幂等：patch 里已有 ">>> wildfire preset mode" 标记则直接返回。
 * 写入前备份 cordis.patch.yml 为 cordis.patch.yml.bak-<时间戳>。
 *
 * 用法： node scripts/enable-presets.mjs <profileDir> [dshPackageDir]
 *   profileDir     例如 ~/.dsh/profiles/wildfire
 *   dshPackageDir  @deepseek-ai/dsh 包目录（默认从 `which dsh` 推导）
 */
import { existsSync, readFileSync, writeFileSync, copyFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { realpathSync } from 'node:fs';

const MARK_BEGIN = '# >>> wildfire preset mode (generated by scripts/enable-presets.mjs; 由 build-deploy.sh 维护)';
const MARK_END = '# <<< wildfire preset mode';

function fail(msg) {
  console.error(`[enable-presets] ${msg}`);
  process.exit(1);
}

const profileDir = process.argv[2] ? resolve(process.argv[2]) : '';
if (!profileDir) fail('缺少 profileDir 参数（例：~/.dsh/profiles/wildfire）');
const patchPath = join(profileDir, 'cordis.patch.yml');
if (!existsSync(patchPath)) fail(`找不到 ${patchPath}`);

let patch = readFileSync(patchPath, 'utf8');
// 幂等：已有旧块则先摘掉再按最新规则重建（便于升级，例如补 cordis 依赖行/自定义 preset）
if (patch.includes(MARK_BEGIN)) {
  const start = patch.indexOf(MARK_BEGIN);
  const end = patch.indexOf(MARK_END);
  if (end < 0) fail('patch 里有起始标记但没有结束标记，请手工检查');
  patch = `${patch.slice(0, start)}${patch.slice(end + MARK_END.length).replace(/^\n+/, '')}`;
  console.log('[enable-presets] 检测到旧块，重建');
}

// 定位 @deepseek-ai/dsh 包目录（lib/bin.js 的上两级）
function dshPackageDir() {
  if (process.argv[3]) return resolve(process.argv[3]);
  let bin = '';
  try {
    bin = execFileSync('which', ['dsh'], { encoding: 'utf8' }).trim();
  } catch {
    // ignore
  }
  if (!bin) fail('找不到 dsh 命令，请把 dsh 包目录作为第二个参数传入');
  const real = realpathSync(bin);
  return dirname(dirname(real)); // <pkg>/lib/bin.js -> <pkg>
}

const dshPkg = dshPackageDir();
const modules = join(dshPkg, 'node_modules', '@deepseek-ai');
const webApp = join(modules, 'dsh-web-app');
if (!existsSync(join(webApp, 'cordis.patch.yml'))) fail(`找不到 ${webApp}/cordis.patch.yml`);

// 1) 禁用 agent 平面行：从 web-app 的 patch 里抽取 `- id: X` + `disabled: true` 成对条目
const webLines = readFileSync(join(webApp, 'cordis.patch.yml'), 'utf8').split('\n');
const disabledIds = [];
for (let i = 0; i < webLines.length; i++) {
  const m = webLines[i].match(/^- id:\s*(\S+)\s*$/);
  if (!m) continue;
  const next = (webLines[i + 1] || '').trim();
  if (next === 'disabled: true') disabledIds.push(m[1]);
}
if (disabledIds.length === 0) fail('未能从 dsh-web-app 的 patch 中解析出禁用清单');

// 2) 4 个 preset 定义（web-app bundle 的 dsh.bundle.patch 顺序）
const presetNames = ['standard', 'ptc', 'minimal', 'cordis'];
const presetYaml = presetNames
  .map((n) => {
    const p = join(webApp, 'presets', `${n}.patch.yml`);
    if (!existsSync(p)) fail(`找不到 preset 定义 ${p}`);
    return readFileSync(p, 'utf8').trimEnd();
  })
  .join('\n\n');

// 3) 其它 profile 的 vendor bundle 里声明的自定义 preset（如 dsh-deploy-advisor）：
//    它们的 patch 只含 preset 定义，skills 已装在共享的 $DSH_HOME/skills，直接带过来即可。
const homeDir = dirname(dirname(profileDir));
const profilesRoot = join(homeDir, 'profiles');
let vendorPresets = '';
try {
  for (const p of readdirSync(profilesRoot)) {
    const vendorDir = join(profilesRoot, p, 'vendor');
    if (!existsSync(vendorDir)) continue;
    for (const v of readdirSync(vendorDir)) {
      const f = join(vendorDir, v, 'cordis.patch.yml');
      if (!existsSync(f)) continue;
      const text = readFileSync(f, 'utf8');
      if (!text.includes('@deepseek-ai/dsh-agent-preset')) continue;
      const start = text.search(/^- insert:/m);
      if (start < 0) continue;
      vendorPresets += `\n# ── 自定义 preset（来自 ${p}/vendor/${v}）──\n${text.slice(start).trimEnd()}\n`;
    }
  }
} catch {
  // vendor 目录不可读：忽略，只带官方 preset
}

const block = [
  MARK_BEGIN,
  ...disabledIds.flatMap((id) => [`- id: ${id}`, '  disabled: true']),
  '',
  '- insert:',
  '    # standard preset 内的 tool-subagent 依赖该 Host 模块；缺失会导致整个 preset 挂载失败',
  '    - id: subagent-model-selection-settings',
  "      name: '@deepseek-ai/dsh-tool-subagent/model-selection-settings'",
  '    # agentPresets 服务（dsh 0.2+）：AI 面板「Agent 模式」的档位来源',
  '    - id: agent-preset-registry',
  "      name: '@deepseek-ai/dsh-agent-preset-registry'",
  '      config:',
  '        default: standard',
  '    # 创造模式（cordis preset）的 Host 依赖：缺这两行时该 preset 挂载失败、',
  '    # 会被 registry 标记 broken 并从面板可选项里过滤掉（只显示其余 3 个）。',
  '    - id: cordis-host-runner',
  "      name: '@deepseek-ai/dsh-cordis-host-runner'",
  '    - id: cordis-inspect-providers',
  "      name: '@deepseek-ai/dsh-tool-cordis/host'",
  '',
  presetYaml,
  ...(vendorPresets ? [vendorPresets] : []),
  MARK_END,
  '',
].join('\n');

const backup = `${patchPath}.bak-${Date.now()}`;
copyFileSync(patchPath, backup);
writeFileSync(patchPath, `${block}\n${patch}`, 'utf8');
const vendorCount = (vendorPresets.match(/^    - id: preset-/gm) || []).length;
console.log(
  `[enable-presets] 已启用 preset 模式：禁用 ${disabledIds.length} 行 + 插入 registry + ` +
    `${presetNames.length} 个官方 preset${vendorCount ? ` + ${vendorCount} 个自定义 preset` : ''}`
);
console.log(`[enable-presets] 原 patch 备份：${backup}`);
